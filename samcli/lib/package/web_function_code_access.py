"""
Checks that an S3 bucket can hold AWS::Serverless::WebFunction code.

Lambda reads Web Function code from S3 with the lambda.amazonaws.com service principal, so the bucket must be
versioned, its policy must let that principal read the objects, and an SSE-KMS key must be a customer managed key
whose policy lets the principal decrypt.

An unversioned bucket and an AWS managed key always make Lambda reject the revision, so they fail packaging. Other
problems are warnings: policy conditions and other access paths can't be fully evaluated here, and Lambda rejects the
revision with a clear error if access is missing.
"""

import fnmatch
import json
import logging
from typing import Any, Dict, Iterable, List, Optional, Tuple

import click
from botocore.exceptions import ClientError

from samcli.commands.exceptions import UserException
from samcli.lib.cfn_language_extensions.utils import is_foreach_key
from samcli.lib.providers.provider import Stack
from samcli.lib.utils.resources import AWS_SERVERLESS_WEBFUNCTION

LOG = logging.getLogger(__name__)

LAMBDA_SERVICE_PRINCIPAL = "lambda.amazonaws.com"
REQUIRED_S3_ACTIONS = ("s3:GetObject", "s3:GetObjectVersion")
EXAMPLE_POLICY_DOCS = (
    "https://docs.aws.amazon.com/lambda/latest/dg/web-functions-code-s3.html#web-functions-code-s3-bucket-policy"
)


class WebFunctionInForEachError(UserException):
    """An AWS::Serverless::WebFunction with local code is generated by Fn::ForEach, which isn't supported yet."""

    def __init__(self, resources: List[str]):
        super().__init__(
            message=(
                "AWS::Serverless::WebFunction resources with local code aren't supported inside Fn::ForEach yet: "
                f"{', '.join(resources)}. Define them outside Fn::ForEach, or point their CodeUri at code that's "
                "already in S3."
            )
        )


def check_no_web_functions_in_foreach(stacks: Iterable[Stack]) -> None:
    """
    Raise WebFunctionInForEachError if a Fn::ForEach generates an AWS::Serverless::WebFunction with local code.

    Only templates that SAM CLI expanded locally with language extensions keep their original template, so other
    templates are never affected.
    """
    found: List[str] = []
    for stack in stacks:
        original = getattr(stack, "original_template_dict", None)
        if not isinstance(original, dict):
            continue
        for key in _web_functions_in_foreach(original.get("Resources") or {}):
            found.append(f"{stack.stack_path}/{key}" if stack.stack_path else key)
    if found:
        raise WebFunctionInForEachError(found)


def _web_functions_in_foreach(resources: Dict[str, Any], inside_foreach: bool = False) -> List[str]:
    """Return the keys of Web Functions with local code defined in Fn::ForEach blocks, including nested ones."""
    found: List[str] = []
    for key, value in resources.items():
        if is_foreach_key(key):
            # Fn::ForEach::<name>: [identifier, collection, output template]
            if isinstance(value, list) and len(value) >= 3 and isinstance(value[2], dict):  # noqa: PLR2004
                found.extend(_web_functions_in_foreach(value[2], inside_foreach=True))
            continue
        if inside_foreach and isinstance(value, dict) and value.get("Type") == AWS_SERVERLESS_WEBFUNCTION:
            if _has_local_code((value.get("Properties") or {}).get("CodeUri")):
                found.append(key)
    return found


def _has_local_code(code_uri: Any) -> bool:
    if isinstance(code_uri, str):
        return not code_uri.startswith("s3://")
    return not (isinstance(code_uri, dict) and "Bucket" in code_uri)


def stacks_have_web_functions(stacks: Iterable[Stack], local_code_only: bool = False) -> bool:
    """
    Return True if any of the stacks (including nested stacks) defines an AWS::Serverless::WebFunction.

    Parameters
    ----------
    stacks : Iterable[Stack]
        Stacks to search, as returned by SamLocalStackProvider.get_stacks
    local_code_only : bool
        Only count Web Functions whose CodeUri is a local path, which packaging uploads
    """
    for stack in stacks:
        for resource in (stack.resources or {}).values():
            if not isinstance(resource, dict) or resource.get("Type") != AWS_SERVERLESS_WEBFUNCTION:
                continue
            if not local_code_only:
                return True
            code_uri = (resource.get("Properties") or {}).get("CodeUri")
            if not isinstance(code_uri, dict) and _has_local_code(code_uri):
                return True
    return False


def template_file_has_local_web_functions(template_file: str, language_extensions_enabled: bool = False) -> bool:
    """
    Return True if the template file, or a nested stack it references, defines an AWS::Serverless::WebFunction with
    local code. Returns False if the template can't be read, which fails later with a clearer error.
    """
    # Imported here to avoid a circular import
    from samcli.lib.providers.sam_stack_provider import SamLocalStackProvider  # pylint: disable=import-outside-toplevel

    try:
        stacks, _ = SamLocalStackProvider.get_stacks(
            template_file, language_extensions_enabled=language_extensions_enabled
        )
        return stacks_have_web_functions(stacks, local_code_only=True)
    except Exception:  # pylint: disable=broad-except
        LOG.debug("Could not load stacks from %s to look for Web Functions", template_file, exc_info=True)
        return False


class WebFunctionCodeBucketError(UserException):
    """The bucket or KMS key can't serve Web Function code, so Lambda would reject the revision."""

    def __init__(self, problems: List[str]):
        problem_lines = "\n".join(f"- {problem}" for problem in problems)
        super().__init__(message=f"Lambda Web Functions can't read code uploaded with these settings:\n{problem_lines}")


def check_web_function_code_bucket(
    s3_client: Any,
    bucket: str,
    prefix: Optional[str] = None,
    kms_key_id: Optional[str] = None,
    kms_client: Optional[Any] = None,
) -> List[str]:
    """
    Check that the bucket can serve Web Function code.

    Raises WebFunctionCodeBucketError if the bucket isn't versioned or the KMS key is an AWS managed key. Prints a
    warning for each other problem, to stderr so it doesn't corrupt --output json or a packaged template written to
    stdout, and returns the warnings.
    """
    errors: List[str] = []
    warnings: List[str] = []
    for check_errors, check_warnings in (
        _check_versioning(s3_client, bucket),
        _check_bucket_policy(s3_client, bucket, prefix),
        _check_kms_key(kms_client, kms_key_id) if kms_key_id and kms_client is not None else ([], []),
    ):
        errors.extend(check_errors)
        warnings.extend(check_warnings)
    for warning in warnings:
        click.secho(f"\n\tWarning: {warning}", fg="yellow", err=True)
    if errors:
        raise WebFunctionCodeBucketError(errors)
    return warnings


def _check_versioning(s3_client: Any, bucket: str) -> Tuple[List[str], List[str]]:
    """Return (errors, warnings)."""
    try:
        status = s3_client.get_bucket_versioning(Bucket=bucket).get("Status")
    except ClientError as ex:
        LOG.debug("Could not read versioning for bucket %s", bucket, exc_info=ex)
        return [], [
            f"Couldn't check that S3 bucket {bucket} has versioning enabled, which Lambda Web Functions require."
        ]
    if status != "Enabled":
        return [
            f"S3 bucket {bucket} doesn't have versioning enabled. Lambda Web Functions require a versioned code "
            "bucket; enable versioning on it or use another bucket."
        ], []
    return [], []


def _check_bucket_policy(s3_client: Any, bucket: str, prefix: Optional[str]) -> Tuple[List[str], List[str]]:
    """Return (errors, warnings). Policy problems are only warnings because the check is a heuristic."""
    missing_message = (
        f"The policy of S3 bucket {bucket} doesn't allow {LAMBDA_SERVICE_PRINCIPAL} to call "
        f"{' and '.join(REQUIRED_S3_ACTIONS)} on the uploaded code, so Lambda Web Functions can't read it. "
        f"For an example policy, see {EXAMPLE_POLICY_DOCS}"
    )
    try:
        policy = json.loads(s3_client.get_bucket_policy(Bucket=bucket)["Policy"])
    except ClientError as ex:
        if ex.response.get("Error", {}).get("Code") == "NoSuchBucketPolicy":
            return [], [missing_message]
        LOG.debug("Could not read the policy of bucket %s", bucket, exc_info=ex)
        return [], [
            f"Couldn't read the policy of S3 bucket {bucket} to check that {LAMBDA_SERVICE_PRINCIPAL} can read "
            "Lambda Web Function code."
        ]
    key = f"{prefix.strip('/')}/code" if prefix else "code"
    if all(_policy_allows(policy, action, bucket, key) for action in REQUIRED_S3_ACTIONS):
        return [], []
    return [], [missing_message]


def _check_kms_key(kms_client: Any, kms_key_id: str) -> Tuple[List[str], List[str]]:
    """Return (errors, warnings). An AWS managed key is an error; key policy problems are warnings."""
    try:
        metadata = kms_client.describe_key(KeyId=kms_key_id)["KeyMetadata"]
    except ClientError as ex:
        LOG.debug("Could not describe KMS key %s", kms_key_id, exc_info=ex)
        return [], [
            f"Couldn't check KMS key {kms_key_id}, which Lambda must be able to use to decrypt Web Function code."
        ]
    if metadata.get("KeyManager") == "AWS":
        return [
            f"KMS key {kms_key_id} is an AWS managed key. Lambda Web Functions can't read code encrypted with it; use "
            f"a customer managed key whose key policy allows {LAMBDA_SERVICE_PRINCIPAL} to call kms:Decrypt."
        ], []
    try:
        policy = json.loads(kms_client.get_key_policy(KeyId=metadata["KeyId"], PolicyName="default")["Policy"])
    except ClientError as ex:
        LOG.debug("Could not read the policy of KMS key %s", kms_key_id, exc_info=ex)
        return [], [f"Couldn't read the policy of KMS key {kms_key_id} to check that Lambda can decrypt with it."]
    if not _policy_allows(policy, "kms:Decrypt"):
        return [], [
            f"The policy of KMS key {kms_key_id} doesn't allow {LAMBDA_SERVICE_PRINCIPAL} to call kms:Decrypt, so "
            "Lambda Web Functions can't read code encrypted with it."
        ]
    return [], []


def _policy_allows(policy: Dict[str, Any], action: str, bucket: Optional[str] = None, key: str = "") -> bool:
    """
    Return True if an Allow statement grants the action to the Lambda service principal.

    Conditions are not evaluated. For S3, the statement's Resource must match an object in the bucket under the key.
    """
    statements = policy.get("Statement", [])
    if isinstance(statements, dict):
        statements = [statements]
    for statement in statements:
        if not isinstance(statement, dict) or statement.get("Effect") != "Allow":
            continue
        if not _principal_includes_lambda(statement.get("Principal")):
            continue
        if not any(
            fnmatch.fnmatchcase(action.lower(), pattern.lower()) for pattern in _as_list(statement.get("Action"))
        ):
            continue
        if bucket is None or any(
            _resource_matches(pattern, bucket, key) for pattern in _as_list(statement.get("Resource"))
        ):
            return True
    return False


def _principal_includes_lambda(principal: Any) -> bool:
    if principal == "*":
        return True
    if isinstance(principal, dict):
        return "*" in _as_list(principal.get("AWS")) or LAMBDA_SERVICE_PRINCIPAL in _as_list(principal.get("Service"))
    return False


def _resource_matches(pattern: str, bucket: str, key: str) -> bool:
    if pattern == "*":
        return True
    parts = pattern.split(":", 5)
    if len(parts) != 6 or parts[0] != "arn" or parts[2] != "s3":  # noqa: PLR2004
        return False
    return fnmatch.fnmatchcase(f"{bucket}/{key}", parts[5])


def _as_list(value: Any) -> List[Any]:
    if value is None:
        return []
    return value if isinstance(value, list) else [value]
